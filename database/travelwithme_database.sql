-- ============================================================
-- TravelWithMe - PostgreSQL 16 Database Schema
-- Version: 1.0
-- Purpose: Travel marketplace (hotel, tour, bus, flight, train)
-- Database name: travelwithme
--
-- Run:
--   1) Create database travelwithme;
--   2) Connect to travelwithme
--   3) Execute this file with psql or pgAdmin Query Tool.
--
-- Notes:
-- - Prices are stored in VND by default; currency_code is retained for extension.
-- - This schema stores booking/payment records, not card numbers or CVV.
-- - Real inventory reservation must be done transactionally by the backend.
-- ============================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS roles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(40) NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL,
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO roles (code, name, description) VALUES
 ('CUSTOMER', 'Customer', 'Người tìm kiếm và đặt dịch vụ du lịch'),
 ('PARTNER', 'Partner', 'Đối tác cung cấp khách sạn, tour hoặc phương tiện'),
 ('ADMIN', 'Administrator', 'Quản trị toàn hệ thống'),
 ('SUPPORT', 'Customer Support', 'Nhân viên hỗ trợ khách hàng')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE IF NOT EXISTS users (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email               VARCHAR(255) NOT NULL,
    phone               VARCHAR(30),
    password_hash       TEXT,
    full_name           VARCHAR(160) NOT NULL,
    date_of_birth       DATE,
    gender              VARCHAR(20),
    avatar_url          TEXT,
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE','PENDING','SUSPENDED','DELETED')),
    email_verified_at   TIMESTAMPTZ,
    phone_verified_at   TIMESTAMPTZ,
    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at          TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_lower ON users (LOWER(email));
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_phone ON users (phone) WHERE phone IS NOT NULL;

CREATE TABLE IF NOT EXISTS user_roles (
    user_id     UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id     BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS user_addresses (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    label           VARCHAR(80),
    recipient_name  VARCHAR(160) NOT NULL,
    phone           VARCHAR(30) NOT NULL,
    address_line    TEXT NOT NULL,
    ward            VARCHAR(120),
    district        VARCHAR(120),
    city            VARCHAR(120) NOT NULL,
    province        VARCHAR(120),
    country_code    CHAR(2) NOT NULL DEFAULT 'VN',
    is_default      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_user_addresses_user ON user_addresses(user_id);

CREATE TABLE IF NOT EXISTS partner_profiles (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             UUID NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    business_name       VARCHAR(200) NOT NULL,
    business_type       VARCHAR(30) NOT NULL
                        CHECK (business_type IN ('HOTEL','TOUR_OPERATOR','TRANSPORT_OPERATOR','AGENCY','OTHER')),
    tax_code            VARCHAR(80),
    contact_email       VARCHAR(255),
    contact_phone       VARCHAR(30),
    description         TEXT,
    verification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                        CHECK (verification_status IN ('PENDING','APPROVED','REJECTED','SUSPENDED')),
    verified_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS destinations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id       BIGINT REFERENCES destinations(id) ON DELETE SET NULL,
    name            VARCHAR(180) NOT NULL,
    slug            VARCHAR(220) NOT NULL UNIQUE,
    destination_type VARCHAR(30) NOT NULL DEFAULT 'CITY'
                    CHECK (destination_type IN ('COUNTRY','REGION','PROVINCE','CITY','ATTRACTION')),
    country_code    CHAR(2) NOT NULL DEFAULT 'VN',
    description     TEXT,
    latitude        NUMERIC(10,7),
    longitude       NUMERIC(10,7),
    cover_image_url TEXT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_destinations_parent ON destinations(parent_id);
CREATE INDEX IF NOT EXISTS ix_destinations_name ON destinations USING GIN (to_tsvector('simple', name));

CREATE TABLE IF NOT EXISTS media_assets (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_user_id   UUID REFERENCES users(id) ON DELETE SET NULL,
    url             TEXT NOT NULL,
    storage_key     TEXT,
    media_type      VARCHAR(20) NOT NULL DEFAULT 'IMAGE'
                    CHECK (media_type IN ('IMAGE','VIDEO','DOCUMENT')),
    alt_text        VARCHAR(255),
    sort_order      INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------- HOTELS ----------------------------
CREATE TABLE IF NOT EXISTS hotels (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    partner_id          UUID NOT NULL REFERENCES partner_profiles(id) ON DELETE RESTRICT,
    destination_id      BIGINT REFERENCES destinations(id) ON DELETE SET NULL,
    name                VARCHAR(220) NOT NULL,
    slug                VARCHAR(240) NOT NULL UNIQUE,
    description         TEXT,
    star_rating         SMALLINT CHECK (star_rating BETWEEN 1 AND 5),
    address_line        TEXT NOT NULL,
    ward                VARCHAR(120),
    district            VARCHAR(120),
    city                VARCHAR(120) NOT NULL,
    province            VARCHAR(120),
    country_code        CHAR(2) NOT NULL DEFAULT 'VN',
    latitude            NUMERIC(10,7),
    longitude           NUMERIC(10,7),
    check_in_time       TIME,
    check_out_time      TIME,
    status              VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT','PENDING_REVIEW','PUBLISHED','REJECTED','INACTIVE')),
    average_rating      NUMERIC(3,2) NOT NULL DEFAULT 0 CHECK (average_rating BETWEEN 0 AND 5),
    review_count        INTEGER NOT NULL DEFAULT 0 CHECK (review_count >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_hotels_destination_status ON hotels(destination_id, status);
CREATE INDEX IF NOT EXISTS ix_hotels_partner ON hotels(partner_id);
CREATE INDEX IF NOT EXISTS ix_hotels_city ON hotels(city);

CREATE TABLE IF NOT EXISTS hotel_amenities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE,
    icon        VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS hotel_amenity_map (
    hotel_id    UUID NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
    amenity_id  BIGINT NOT NULL REFERENCES hotel_amenities(id) ON DELETE RESTRICT,
    PRIMARY KEY (hotel_id, amenity_id)
);
CREATE TABLE IF NOT EXISTS hotel_images (
    hotel_id    UUID NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
    media_id    UUID NOT NULL REFERENCES media_assets(id) ON DELETE CASCADE,
    is_cover    BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (hotel_id, media_id)
);

CREATE TABLE IF NOT EXISTS room_types (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    hotel_id        UUID NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
    name            VARCHAR(160) NOT NULL,
    description     TEXT,
    max_adults      SMALLINT NOT NULL DEFAULT 2 CHECK (max_adults > 0),
    max_children    SMALLINT NOT NULL DEFAULT 0 CHECK (max_children >= 0),
    bed_description VARCHAR(160),
    room_size_m2    NUMERIC(7,2) CHECK (room_size_m2 > 0),
    total_rooms     INTEGER NOT NULL CHECK (total_rooms >= 0),
    amenities       JSONB NOT NULL DEFAULT '[]'::jsonb,
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hotel_id, name)
);
CREATE INDEX IF NOT EXISTS ix_room_types_hotel ON room_types(hotel_id);

CREATE TABLE IF NOT EXISTS hotel_room_rates (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    room_type_id        UUID NOT NULL REFERENCES room_types(id) ON DELETE CASCADE,
    rate_name           VARCHAR(120) NOT NULL DEFAULT 'Standard',
    meal_plan           VARCHAR(30) NOT NULL DEFAULT 'ROOM_ONLY'
                        CHECK (meal_plan IN ('ROOM_ONLY','BREAKFAST','HALF_BOARD','FULL_BOARD')),
    cancellation_policy TEXT,
    price_per_night     NUMERIC(14,2) NOT NULL CHECK (price_per_night >= 0),
    currency_code       CHAR(3) NOT NULL DEFAULT 'VND',
    valid_from          DATE,
    valid_to            DATE,
    is_refundable       BOOLEAN NOT NULL DEFAULT TRUE,
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);

CREATE TABLE IF NOT EXISTS hotel_inventory (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    room_type_id    UUID NOT NULL REFERENCES room_types(id) ON DELETE CASCADE,
    stay_date       DATE NOT NULL,
    rooms_total     INTEGER NOT NULL CHECK (rooms_total >= 0),
    rooms_reserved  INTEGER NOT NULL DEFAULT 0 CHECK (rooms_reserved >= 0),
    rooms_blocked   INTEGER NOT NULL DEFAULT 0 CHECK (rooms_blocked >= 0),
    price_override  NUMERIC(14,2) CHECK (price_override >= 0),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (room_type_id, stay_date),
    CHECK (rooms_reserved + rooms_blocked <= rooms_total)
);
CREATE INDEX IF NOT EXISTS ix_hotel_inventory_date ON hotel_inventory(stay_date);

-- -------------------------- TOURS ----------------------------
CREATE TABLE IF NOT EXISTS tours (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    partner_id          UUID NOT NULL REFERENCES partner_profiles(id) ON DELETE RESTRICT,
    destination_id      BIGINT REFERENCES destinations(id) ON DELETE SET NULL,
    title               VARCHAR(220) NOT NULL,
    slug                VARCHAR(240) NOT NULL UNIQUE,
    description         TEXT,
    duration_days       SMALLINT NOT NULL DEFAULT 1 CHECK (duration_days > 0),
    duration_nights     SMALLINT NOT NULL DEFAULT 0 CHECK (duration_nights >= 0),
    departure_location  VARCHAR(220),
    included_services   JSONB NOT NULL DEFAULT '[]'::jsonb,
    excluded_services   JSONB NOT NULL DEFAULT '[]'::jsonb,
    itinerary           JSONB NOT NULL DEFAULT '[]'::jsonb,
    min_participants    SMALLINT NOT NULL DEFAULT 1 CHECK (min_participants > 0),
    status              VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT','PENDING_REVIEW','PUBLISHED','REJECTED','INACTIVE')),
    average_rating      NUMERIC(3,2) NOT NULL DEFAULT 0 CHECK (average_rating BETWEEN 0 AND 5),
    review_count        INTEGER NOT NULL DEFAULT 0 CHECK (review_count >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_tours_destination_status ON tours(destination_id, status);
CREATE INDEX IF NOT EXISTS ix_tours_partner ON tours(partner_id);

CREATE TABLE IF NOT EXISTS tour_departures (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tour_id             UUID NOT NULL REFERENCES tours(id) ON DELETE CASCADE,
    start_at            TIMESTAMPTZ NOT NULL,
    end_at              TIMESTAMPTZ,
    meeting_point       TEXT,
    capacity            INTEGER NOT NULL CHECK (capacity > 0),
    seats_reserved      INTEGER NOT NULL DEFAULT 0 CHECK (seats_reserved >= 0),
    price_per_adult     NUMERIC(14,2) NOT NULL CHECK (price_per_adult >= 0),
    price_per_child     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (price_per_child >= 0),
    currency_code       CHAR(3) NOT NULL DEFAULT 'VND',
    status              VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
                        CHECK (status IN ('SCHEDULED','SOLD_OUT','CANCELLED','COMPLETED')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (end_at IS NULL OR end_at >= start_at),
    CHECK (seats_reserved <= capacity)
);
CREATE INDEX IF NOT EXISTS ix_tour_departures_tour_start ON tour_departures(tour_id, start_at);
CREATE TABLE IF NOT EXISTS tour_images (
    tour_id      UUID NOT NULL REFERENCES tours(id) ON DELETE CASCADE,
    media_id     UUID NOT NULL REFERENCES media_assets(id) ON DELETE CASCADE,
    is_cover     BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order   INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (tour_id, media_id)
);

-- -------------------- TRANSPORT PRODUCTS ---------------------
CREATE TABLE IF NOT EXISTS transport_operators (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    partner_id          UUID REFERENCES partner_profiles(id) ON DELETE RESTRICT,
    name                VARCHAR(220) NOT NULL,
    transport_type      VARCHAR(20) NOT NULL
                        CHECK (transport_type IN ('BUS','FLIGHT','TRAIN')),
    description         TEXT,
    support_phone       VARCHAR(30),
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_transport_operators_type ON transport_operators(transport_type);

CREATE TABLE IF NOT EXISTS transport_stations (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code            VARCHAR(30) UNIQUE,
    name            VARCHAR(220) NOT NULL,
    station_type    VARCHAR(20) NOT NULL
                    CHECK (station_type IN ('BUS_STATION','AIRPORT','RAILWAY_STATION')),
    destination_id  BIGINT REFERENCES destinations(id) ON DELETE SET NULL,
    address_line    TEXT,
    city            VARCHAR(120) NOT NULL,
    country_code    CHAR(2) NOT NULL DEFAULT 'VN',
    latitude        NUMERIC(10,7),
    longitude       NUMERIC(10,7),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS transport_routes (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    operator_id         UUID NOT NULL REFERENCES transport_operators(id) ON DELETE RESTRICT,
    origin_station_id   UUID NOT NULL REFERENCES transport_stations(id) ON DELETE RESTRICT,
    destination_station_id UUID NOT NULL REFERENCES transport_stations(id) ON DELETE RESTRICT,
    estimated_minutes   INTEGER CHECK (estimated_minutes > 0),
    distance_km         NUMERIC(9,2) CHECK (distance_km > 0),
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (origin_station_id <> destination_station_id)
);
CREATE INDEX IF NOT EXISTS ix_transport_routes_lookup
    ON transport_routes(origin_station_id, destination_station_id);

CREATE TABLE IF NOT EXISTS transport_departures (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    route_id            UUID NOT NULL REFERENCES transport_routes(id) ON DELETE RESTRICT,
    departure_code      VARCHAR(100),
    vehicle_label       VARCHAR(160),
    departure_at        TIMESTAMPTZ NOT NULL,
    arrival_at          TIMESTAMPTZ,
    boarding_address    TEXT,
    dropoff_address     TEXT,
    total_seats         INTEGER NOT NULL CHECK (total_seats > 0),
    seats_reserved      INTEGER NOT NULL DEFAULT 0 CHECK (seats_reserved >= 0),
    base_price          NUMERIC(14,2) NOT NULL CHECK (base_price >= 0),
    currency_code       CHAR(3) NOT NULL DEFAULT 'VND',
    status              VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
                        CHECK (status IN ('SCHEDULED','SOLD_OUT','CANCELLED','COMPLETED')),
    provider_reference  VARCHAR(180),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (arrival_at IS NULL OR arrival_at >= departure_at),
    CHECK (seats_reserved <= total_seats)
);
CREATE INDEX IF NOT EXISTS ix_transport_departures_search
    ON transport_departures(route_id, departure_at, status);

CREATE TABLE IF NOT EXISTS transport_seats (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    departure_id    UUID NOT NULL REFERENCES transport_departures(id) ON DELETE CASCADE,
    seat_code       VARCHAR(30) NOT NULL,
    seat_class      VARCHAR(40) NOT NULL DEFAULT 'STANDARD',
    price_extra     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (price_extra >= 0),
    status          VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
                    CHECK (status IN ('AVAILABLE','BLOCKED','MAINTENANCE')),
    UNIQUE (departure_id, seat_code)
);
CREATE INDEX IF NOT EXISTS ix_transport_seats_departure ON transport_seats(departure_id, status);

-- ------------------------- BOOKINGS --------------------------
CREATE TABLE IF NOT EXISTS bookings (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    booking_code        VARCHAR(24) NOT NULL UNIQUE,
    user_id             UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    contact_name        VARCHAR(160) NOT NULL,
    contact_email       VARCHAR(255) NOT NULL,
    contact_phone       VARCHAR(30) NOT NULL,
    status              VARCHAR(24) NOT NULL DEFAULT 'PENDING_PAYMENT'
                        CHECK (status IN ('PENDING_PAYMENT','CONFIRMED','PARTIALLY_CANCELLED','CANCELLED','COMPLETED','EXPIRED','FAILED')),
    subtotal_amount     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (subtotal_amount >= 0),
    discount_amount     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount          NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    service_fee         NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (service_fee >= 0),
    total_amount        NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    currency_code       CHAR(3) NOT NULL DEFAULT 'VND',
    customer_note       TEXT,
    expires_at          TIMESTAMPTZ,
    confirmed_at        TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (discount_amount <= subtotal_amount + tax_amount + service_fee)
);
CREATE INDEX IF NOT EXISTS ix_bookings_user_created ON bookings(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_bookings_status_created ON bookings(status, created_at DESC);

CREATE TABLE IF NOT EXISTS booking_items (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    booking_id          UUID NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    item_type           VARCHAR(20) NOT NULL
                        CHECK (item_type IN ('HOTEL','TOUR','BUS','FLIGHT','TRAIN')),
    item_name_snapshot  VARCHAR(240) NOT NULL,
    description_snapshot TEXT,
    quantity            INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price          NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    total_price         NUMERIC(14,2) NOT NULL CHECK (total_price >= 0),
    currency_code       CHAR(3) NOT NULL DEFAULT 'VND',
    status              VARCHAR(24) NOT NULL DEFAULT 'PENDING'
                        CHECK (status IN ('PENDING','CONFIRMED','CANCELLED','COMPLETED','FAILED')),
    cancellation_policy_snapshot TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_booking_items_booking ON booking_items(booking_id);

CREATE TABLE IF NOT EXISTS hotel_booking_details (
    booking_item_id UUID PRIMARY KEY REFERENCES booking_items(id) ON DELETE CASCADE,
    hotel_id        UUID NOT NULL REFERENCES hotels(id) ON DELETE RESTRICT,
    room_type_id    UUID NOT NULL REFERENCES room_types(id) ON DELETE RESTRICT,
    rate_id         UUID REFERENCES hotel_room_rates(id) ON DELETE SET NULL,
    check_in_date   DATE NOT NULL,
    check_out_date  DATE NOT NULL,
    rooms_count     INTEGER NOT NULL CHECK (rooms_count > 0),
    adults_count    INTEGER NOT NULL CHECK (adults_count > 0),
    children_count  INTEGER NOT NULL DEFAULT 0 CHECK (children_count >= 0),
    guest_names     JSONB NOT NULL DEFAULT '[]'::jsonb,
    CHECK (check_out_date > check_in_date)
);
CREATE INDEX IF NOT EXISTS ix_hotel_booking_dates ON hotel_booking_details(check_in_date, check_out_date);

CREATE TABLE IF NOT EXISTS tour_booking_details (
    booking_item_id UUID PRIMARY KEY REFERENCES booking_items(id) ON DELETE CASCADE,
    tour_id         UUID NOT NULL REFERENCES tours(id) ON DELETE RESTRICT,
    departure_id    UUID NOT NULL REFERENCES tour_departures(id) ON DELETE RESTRICT,
    adult_count     INTEGER NOT NULL DEFAULT 1 CHECK (adult_count >= 0),
    child_count     INTEGER NOT NULL DEFAULT 0 CHECK (child_count >= 0),
    participant_info JSONB NOT NULL DEFAULT '[]'::jsonb,
    CHECK (adult_count + child_count > 0)
);

CREATE TABLE IF NOT EXISTS transport_booking_details (
    booking_item_id UUID PRIMARY KEY REFERENCES booking_items(id) ON DELETE CASCADE,
    departure_id    UUID NOT NULL REFERENCES transport_departures(id) ON DELETE RESTRICT,
    passenger_info  JSONB NOT NULL DEFAULT '[]'::jsonb,
    seat_codes      JSONB NOT NULL DEFAULT '[]'::jsonb,
    origin_station_id UUID REFERENCES transport_stations(id) ON DELETE SET NULL,
    destination_station_id UUID REFERENCES transport_stations(id) ON DELETE SET NULL,
    ticket_provider_reference VARCHAR(180)
);
CREATE INDEX IF NOT EXISTS ix_transport_booking_departure ON transport_booking_details(departure_id);

CREATE TABLE IF NOT EXISTS booking_status_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      UUID NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    old_status      VARCHAR(24),
    new_status      VARCHAR(24) NOT NULL,
    changed_by      UUID REFERENCES users(id) ON DELETE SET NULL,
    reason          TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_booking_history_booking ON booking_status_history(booking_id, created_at);

-- ---------------------- PAYMENT / REFUND ---------------------
CREATE TABLE IF NOT EXISTS payments (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    booking_id          UUID NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
    payment_reference   VARCHAR(180) UNIQUE,
    provider            VARCHAR(40) NOT NULL
                        CHECK (provider IN ('MOCK','VNPAY','MOMO','ZALOPAY','STRIPE','BANK_TRANSFER','CASH','OTHER')),
    method              VARCHAR(40),
    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                        CHECK (status IN ('PENDING','PROCESSING','SUCCEEDED','FAILED','CANCELLED','EXPIRED')),
    amount              NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    currency_code       CHAR(3) NOT NULL DEFAULT 'VND',
    idempotency_key     VARCHAR(180) UNIQUE,
    provider_transaction_id VARCHAR(220),
    checkout_url        TEXT,
    request_payload     JSONB,
    response_payload    JSONB,
    paid_at             TIMESTAMPTZ,
    failed_at           TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_payments_booking ON payments(booking_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_payments_status ON payments(status);

CREATE TABLE IF NOT EXISTS refunds (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    payment_id          UUID NOT NULL REFERENCES payments(id) ON DELETE RESTRICT,
    booking_id          UUID NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
    requested_by        UUID REFERENCES users(id) ON DELETE SET NULL,
    amount              NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    reason              TEXT NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'REQUESTED'
                        CHECK (status IN ('REQUESTED','APPROVED','REJECTED','PROCESSING','SUCCEEDED','FAILED')),
    provider_refund_id  VARCHAR(220),
    processed_by        UUID REFERENCES users(id) ON DELETE SET NULL,
    processed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_refunds_booking ON refunds(booking_id, created_at DESC);

-- -------------------- COUPONS / PROMOTIONS -------------------
CREATE TABLE IF NOT EXISTS coupons (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code                VARCHAR(60) NOT NULL,
    name                VARCHAR(180) NOT NULL,
    description         TEXT,
    discount_type       VARCHAR(20) NOT NULL
                        CHECK (discount_type IN ('PERCENT','FIXED_AMOUNT')),
    discount_value      NUMERIC(14,2) NOT NULL CHECK (discount_value > 0),
    max_discount_amount NUMERIC(14,2) CHECK (max_discount_amount >= 0),
    min_order_amount    NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (min_order_amount >= 0),
    usage_limit         INTEGER CHECK (usage_limit > 0),
    per_user_limit      INTEGER CHECK (per_user_limit > 0),
